// Pure timing / safety / export logic. Used by the browser app and by tools/build.mjs (Node).
import { ROBOT_KEYS, SIM_KEYS, ALL_KEYS, RANGE, CAP } from "./joints.js";
import { REST_POSE, introText, PHRASES } from "./asanas.js";

export const V_ARM = 0.6;  // planned peak speed for robot joints at tempo 1 (rad/s)
export const V_SIM = 0.8;  // sim-only joints (legs, tilt)
export const BLOCK = 3;    // poses per block before a check-in

export const full = (q) => { const o = {}; ALL_KEYS.forEach((k) => (o[k] = q[k] ?? 0)); return o; };
const maxDelta = (a, b, keys) => Math.max(0, ...keys.map((k) => Math.abs((b[k] ?? 0) - (a[k] ?? 0))));

// Smoothstep peak speed = 1.5 × Δ / T
export function moveDur(a, b, tempo = 1) {
  const arm = (1.5 * maxDelta(a, b, ROBOT_KEYS)) / (V_ARM * tempo);
  const sim = (1.5 * maxDelta(a, b, SIM_KEYS)) / (V_SIM * tempo);
  return Math.max(0.8, arm, sim);
}

// All transitions a pose performs: rest → kf0, then cycling through its keyframes during the hold.
export function transitions(asana) {
  const kf = asana.kf.map(full), out = [[full(REST_POSE), kf[0]]];
  for (let i = 1; i < kf.length; i++) out.push([kf[i - 1], kf[i]]);
  if (kf.length > 1) out.push([kf[kf.length - 1], kf[0]]);
  return out;
}

export function safety(asana, tempo = 1) {
  let peak = 0, peakJ = "", pct = 0, pctJ = "";
  const flags = [];
  for (const q of asana.kf) {
    for (const k of ROBOT_KEYS) {
      const v = q[k] ?? 0, [lo, hi] = RANGE[k];
      if (v < lo || v > hi) flags.push({ lvl: "err", k, msg: `${k} ${v.toFixed(2)} už ribų [${lo}, ${hi}]` });
      const p = v >= 0 ? (hi > 0 ? v / hi : 0) : (lo < 0 ? v / lo : 0);
      if (p > pct) { pct = p; pctJ = k; }
    }
    for (const k of SIM_KEYS) {
      const v = q[k] ?? 0, [lo, hi] = RANGE[k];
      if (v < lo || v > hi) flags.push({ lvl: "err", k, msg: `${k} ${v.toFixed(2)} už ribų (sim)` });
    }
  }
  if (pct > 0.95) flags.push({ lvl: "warn", k: pctJ, msg: `${pctJ} naudoja ${(pct * 100).toFixed(0)}% ribos` });
  for (const [a, b] of transitions(asana)) {
    const T = moveDur(a, b, tempo);
    for (const k of ROBOT_KEYS) { const s = (1.5 * Math.abs(b[k] - a[k])) / T; if (s > peak) { peak = s; peakJ = k; } }
  }
  if (peak > CAP.arm) flags.push({ lvl: "err", k: peakJ, msg: `${peakJ} ${peak.toFixed(2)} rad/s > ${CAP.arm}` });
  return { peak, peakJ, pct, pctJ, flags };
}

// ---------- export to r1ctl (upper body only, 50 Hz) ----------
const speechSec = (t) => Math.max(1.5, t.length * 0.065);

export function buildExport(asanas, lang = "lt", name = "joga", title = "R1 Joga") {
  const rows = [], says = [];
  let t = 0, cur = full(REST_POSE);
  const push = (q) => rows.push([t, ...ROBOT_KEYS.map((k) => q[k])]);
  const move = (b, T) => {
    const a = cur, n = Math.max(1, Math.round(T / 0.02));
    for (let i = 1; i <= n; i++) { let s = i / n; s = s * s * (3 - 2 * s); t += 0.02; const q = {}; for (const k of ROBOT_KEYS) q[k] = a[k] + (b[k] - a[k]) * s; push(q); }
    cur = b;
  };
  const hold = (T) => { const n = Math.round(T / 0.02); for (let i = 0; i < n; i++) { t += 0.02; push(cur); } };
  push(cur);
  says.push({ at: 0, text: PHRASES.welcome[lang] }); hold(speechSec(PHRASES.welcome[lang]));
  asanas.forEach((a, i) => {
    const text = introText(a, lang), start = t;
    says.push({ at: t, text });
    const kf = a.kf.map(full);
    move(kf[0], moveDur(cur, kf[0]));
    hold(Math.max(0, start + speechSec(text) - t));
    const holdEnd = t + a.hold;
    let j = 0;
    while (kf.length > 1 && t < holdEnd - 1) { j = (j + 1) % kf.length; move(kf[j], Math.min(moveDur(cur, kf[j]), Math.max(0.8, holdEnd - t))); }
    if (t < holdEnd) hold(holdEnd - t);
    if ((i + 1) % BLOCK === 0 && i + 1 < asanas.length) {
      const q = ((i + 1) / BLOCK) % 2 ? PHRASES.checkin_continue[lang] : PHRASES.checkin_clear[lang];
      says.push({ at: t, text: q }); hold(4);
    }
  });
  move(full(REST_POSE), moveDur(cur, full(REST_POSE)));
  says.push({ at: t, text: PHRASES.done[lang] }); hold(speechSec(PHRASES.done[lang]));

  const csv = "t," + ROBOT_KEYS_CSV.join(",") + "\n" + rows.map((r) => r.map((v, i) => (i ? v.toFixed(4) : v.toFixed(2))).join(",")).join("\n") + "\n";
  // Spoken track: say + wait steps, run in parallel with the arm trajectory
  const seq = [];
  let tt = 0;
  for (const s of says) { const w = +(s.at - tt).toFixed(1); if (w > 0) seq.push(`        - wait: ${Math.min(60, w)}`); seq.push(`        - say: {text: ${JSON.stringify(s.text)}, voice: eleven}`); tt = s.at; }
  const yaml = [
    `# generated by r1-joga (R1 Jogos Instruktorius). UPPER BODY ONLY: legs stay under Unitree's balance controller.`,
    `# ⚠️ never run on the real robot yet. First: dry run, then gantry, remote in hand, 2 m clear.`,
    `# ⚠️ elbow/shoulder sign conventions were checked on the MuJoCo model only. Check timing of say vs arms on the robot.`,
    `kind: dance`, `title: ${JSON.stringify(title)}`, `category: Yoga`, `emoji: "🧘"`, `seconds: ${t.toFixed(1)}`, `steps:`,
    `- parallel:`, `  - arm_traj:`, `      file: ${name}`, `  - repeat:`, `      times: 1`, `      steps:`, ...seq, `- hand:`, `    side: both`, `    pose: open`, ``,
  ].join("\n");
  return { csv, yaml, seconds: t, rows: rows.length };
}
// r1ctl CSV column names (same order as ROBOT_KEYS)
export const ROBOT_KEYS_CSV = ["lsp", "lsr", "lsy", "le", "lwr", "rsp", "rsr", "rsy", "re", "rwr", "waist_yaw", "head_pitch", "head_yaw"];
